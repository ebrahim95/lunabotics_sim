#!/usr/bin/env python3
"""
Runs the excavator buckets round the belt loop, slaved to the drive roller.

The URDF can't express a belt, so fix_kinematics.py gives every bucket three
joints on the ladder -- <b>_belt_u (along the ladder), <b>_belt_v (across
it) and <b>_belt_rot (about the shafts). This node reads the drive roller
angle from /joint_states, works out where each bucket is on the loop and
sets those joints:

  * Gazebo: Float64MultiArray on /bucket_position_controller/commands, so
    the buckets are real bodies that push on whatever they touch.
  * RViz (display.launch.py): JointState on /bucket_joint_states, which
    joint_state_publisher merges in through its source_list.

Spin the belt by commanding the drive roller, e.g. in Gazebo:
    ros2 topic pub /belt_velocity_controller/commands \
        std_msgs/msg/Float64MultiArray "{data: [2.0]}"
or by dragging the drive_roller_joint slider in the joint_state_publisher GUI.

All geometry comes from config/belt_animator.yaml, which fix_kinematics.py
generates from the CAD -- nothing to tune here.
"""
import math

import rclpy
from rclpy.executors import ExternalShutdownException
from rclpy.node import Node
from sensor_msgs.msg import JointState
from std_msgs.msg import Float64MultiArray

UPDATE_RATE_HZ = 50.0


def loop_pose(s, length, radius):
    """(u, v, theta) at arc length s round the belt loop, in the ladder frame.

    Ladder frame: origin on the bottom shaft, u toward the top shaft, w along
    the shafts, v = w x u. s = 0 is at (0, +r); s grows up the +v side, round
    the top shaft, down the -v side and round the bottom shaft. theta is the
    bucket's rotation about w and keeps counting down lap after lap so the
    continuous joint never jumps. Kept in sync with fix_kinematics.py.
    """
    total = 2 * length + 2 * math.pi * radius
    laps = math.floor(s / total)
    s -= laps * total
    if s < length:
        u, v, th = s, radius, 0.0
    elif s < length + math.pi * radius:
        a = (s - length) / radius
        u, v, th = length + radius * math.sin(a), radius * math.cos(a), -a
    elif s < 2 * length + math.pi * radius:
        u, v, th = length - (s - length - math.pi * radius), -radius, -math.pi
    else:
        a = (s - 2 * length - math.pi * radius) / radius
        u, v, th = -radius * math.sin(a), -radius * math.cos(a), -math.pi - a
    return u, v, th - 2 * math.pi * laps


class BeltAnimator(Node):
    def __init__(self):
        super().__init__("belt_animator")
        self.length = self.declare_parameter("shaft_distance", 0.0).value
        self.radius = self.declare_parameter("pitch_radius", 0.0).value
        self.direction = self.declare_parameter("belt_direction", 1.0).value
        self.drive_joint = self.declare_parameter("drive_joint", "drive_roller_joint").value
        self.buckets = list(self.declare_parameter("buckets", [""]).value)
        self.start = list(self.declare_parameter("start_positions", [0.0]).value)
        if self.length <= 0 or self.radius <= 0 or len(self.buckets) != len(self.start):
            raise RuntimeError(
                "belt_animator needs the parameters from config/belt_animator.yaml "
                "(generated by fix_kinematics.py)")

        self.joint_names = [
            f"{b}_belt_{axis}" for b in self.buckets for axis in ("u", "v", "rot")]
        self.drive_angle = 0.0  # CAD pose until the first joint state arrives

        self.create_subscription(JointState, "/joint_states", self.on_joint_states, 10)
        self.cmd_pub = self.create_publisher(
            Float64MultiArray, "/bucket_position_controller/commands", 10)
        self.js_pub = self.create_publisher(JointState, "/bucket_joint_states", 10)
        self.create_timer(1.0 / UPDATE_RATE_HZ, self.update)
        self.get_logger().info(
            f"Belt animator: {len(self.buckets)} buckets following '{self.drive_joint}' "
            f"(loop {self.length:.3f} m x r={self.radius:.4f} m)")

    def on_joint_states(self, msg):
        if self.drive_joint in msg.name and msg.position:
            self.drive_angle = msg.position[msg.name.index(self.drive_joint)]

    def update(self):
        travel = self.direction * self.radius * self.drive_angle
        positions = []
        for s0 in self.start:
            positions.extend(loop_pose(s0 + travel, self.length, self.radius))

        self.cmd_pub.publish(Float64MultiArray(data=positions))
        js = JointState()
        js.header.stamp = self.get_clock().now().to_msg()
        js.name = self.joint_names
        js.position = positions
        self.js_pub.publish(js)


def main():
    rclpy.init()
    node = BeltAnimator()
    try:
        rclpy.spin(node)
    except (KeyboardInterrupt, ExternalShutdownException):
        pass
    finally:
        node.destroy_node()
        rclpy.try_shutdown()


if __name__ == "__main__":
    main()
